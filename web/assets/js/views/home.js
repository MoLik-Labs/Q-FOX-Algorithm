/** Overview: what this is, what it proves, and where to start. */
import { data, totals, levelKeys, METRIC_HINT } from "../data.js";
import { el, mount, chip, num, int, progressBar } from "../util.js";
import { cubePanel, caseCard, openCase } from "../parts.js";
import { learnedCount, recentSessions } from "../store.js";

export function render() {
  const t = totals();
  const view = el("div");
  let timer = null;

  /* ------------------------------------------------------------- hero cube */
  const showcase = el("div", { class: "hero__cube" });
  const panel = cubePanel({ size: 280, viewToggle: false, reset: false, highlight: "none" });
  showcase.append(panel.node);
  const nowShowing = el("p", { class: "tiny muted", style: { textAlign: "center", maxWidth: "34ch" } },
    "Every case in the book, played on loop");

  const showcaseCases = data.cases
    .filter((c) => c.tokens.length && (c.names.length || (c.count >= 7 && c.count <= 11)))
    .sort(() => 0.5 - Math.random())
    .slice(0, 26);
  let si = 0;

  async function nextShowcase() {
    const row = showcaseCases[si % showcaseCases.length];
    si++;
    const M = data.model;
    // set the case up from solved, then run the algorithm that finishes it
    panel.cube.setState(M.applyIds(M.solved, M.invert(row.tokens)), { keepTransform: false });
    nowShowing.textContent = row.teach
      ? `${row.teach.name} · ${row.family} · ${row.count} moves`
      : `${row.family} · ${row.desc.pattern} · ${row.count} moves`;
    for (const id of row.tokens) {
      await panel.cube.turn(M.byId.get(id).name, 150);
      await wait(60);
    }
    await wait(1500);
    if (timer !== null) nextShowcase();
  }

  const wait = (ms) => new Promise((r) => { timer = setTimeout(r, ms); });

  /* ------------------------------------------------------------------ hero */
  const hero = el("section", { class: "hero" },
    el("div", {},
      el("div", { class: "eyebrow" }, "Q-FOX algorithm engine"),
      el("h1", { class: "hero__title" },
        "Learn the cube by ", el("em", {}, "level"), ",",
        " not by guesswork."),
      el("p", { class: "hero__lede" },
        `Every algorithm here was generated by a solver engine written from
         scratch in C, replayed against its own goal, and exported as data.
         ${int(t.cases)} last-layer cases across ${t.families} families, four
         learning levels from “never solved one” to “fewest moves possible”,
         and ${t.methods} complete methods benchmarked over ${t.scrambles}
         scrambles each.`),
      el("div", { class: "hero__cta" },
        el("a", { class: "btn btn--primary", href: "#/levels/easy" }, "Start at Level 1"),
        el("a", { class: "btn", href: "#/trainer" }, "Open the trainer"),
        el("a", { class: "btn btn--ghost", href: "#/algorithms" }, `Browse ${t.cases} algorithms`)),
      el("div", { class: "hero__facts" },
        chip(`${t.methodsSolvedAll}/${t.methods} methods solved every scramble`, "mint"),
        chip(`book swept to ${t.swept}, exact out to ${t.exactTo}`, "sky"),
        chip(data.check.ok ? "browser cube verified against the engine" : "model mismatch", data.check.ok ? "mint" : "rose"))),
    el("div", {}, showcase, nowShowing));

  /* ----------------------------------------------------------------- stats */
  const stats = el("section", { class: "stats" },
    stat(`${int(t.cases)}`, "algorithm cases", `${t.toLearn} to learn, ${t.named} with a textbook name`, true),
    stat(`${t.levels}`, "levels", "newbie → pro, each with its own curriculum"),
    stat(`${t.methods}`, "methods", "CFOP, Roux, ZZ, Petrus, LBL and the Q-FOX tiers"),
    stat(`${num(t.coverage, 2)}%`, "book coverage", `${int(t.elements)} last-layer elements, swept to depth ${t.swept}`),
    stat(`${t.moves}`, "moves", "outer turns, slices, wide turns and rotations"),
    stat(`${t.fastest ? num(t.fastest.seconds.mean, 2) + " s" : "—"}`, "fastest solve",
         t.fastest ? `${t.fastest.method}, mean over ${t.scrambles} scrambles` : "benchmark pending"));

  /* ---------------------------------------------------------------- levels */
  const levelCards = el("div", { class: "grid grid--4" });
  for (const lv of data.levelsList) {
    const keys = levelKeys(lv.key);
    const done = learnedCount(keys);
    levelCards.append(el("a", { class: "card level-card", href: `#/levels/${lv.key}` },
      el("span", { class: "level-card__n" }, String(lv.title.split(" ")[1] || "")),
      el("div", { class: "card__body" },
        el("div", { class: "card__name" }, lv.title),
        el("div", { class: "card__sub" }, lv.who),
        el("div", { class: "card__sub" }, lv.promise),
        progressBar(done, keys.length, `${done}/${keys.length} learned`),
        el("div", { class: "card__foot" },
          chip(`${lv.algs} engine algorithms`, "fox"),
          chip(`${lv.curriculum.length} study sets`),
          lv.benchmark ? chip(`${num(lv.benchmark.htm, 1)} htm/solve`, "mint") : null))));
  }

  /* --------------------------------------------------------- what's inside */
  const inside = el("section", { class: "grid grid--2" },
    el("div", { class: "panel" },
      el("div", { class: "panel__head" }, el("h3", {}, "Families"),
        el("span", { class: "spacer" }),
        el("a", { class: "btn btn--sm", href: "#/algorithms" }, "Open")),
      el("div", { class: "table-wrap" },
        el("table", { class: "table" },
          el("thead", {}, el("tr", {},
            el("th", {}, "Family"), el("th", {}, "What it solves"),
            el("th", { class: "num" }, "Cases"),
            el("th", { class: "num", title: METRIC_HINT }, "Mean moves"),
            el("th", { class: "num", title: METRIC_HINT }, "Longest"))),
          el("tbody", {}, data.families.map((f) => el("tr", {},
            el("td", { class: "name" },
              el("a", { href: `#/algorithms/${f.key}` }, f.label)),
            el("td", {}, f.goal),
            el("td", { class: "num", title: `${f.non_trivial} worth memorising, ${f.cases - f.non_trivial} already at the goal` }, String(f.non_trivial)),
            el("td", { class: "num", title: METRIC_HINT }, `${num(f.mean, 2)}`),
            el("td", { class: "num", title: METRIC_HINT }, `${f.longest}`))))))),
    el("div", { class: "panel" },
      el("div", { class: "panel__head" }, el("h3", {}, "How a number gets here")),
      el("ol", { class: "small" },
        el("li", {}, el("b", {}, "engine/qfox.c"), " — facelets, coordinates, BFS tables, IDA*, and the last-layer book. The only place cube mechanics exist."),
        el("li", {}, el("b", {}, "qfox/alggen"), " — case families derived by symmetry, not copied from a list: ",
            data.families.map((f) => `${f.non_trivial} ${f.label}`).join(" · "), ", each one an orbit of the symmetry group."),
        el("li", {}, el("b", {}, "the last-layer book"), " — ", int(t.elements), " positions swept exhaustively out to depth ", String(t.swept), ", so ", num(t.coverage, 2), "% of them have a provably shortest answer."),
        el("li", {}, el("b", {}, "scripts/gen_web_data.py"), " — asks the engine for every case, keeps the shortest verified word, writes ", el("code", {}, "web/data/*.json"), "."),
        el("li", {}, el("b", {}, "scripts/validate_web_data.py"), " — replays all ", String(t.cases), " algorithms and re-derives this page's cube geometry from the engine's own permutations."),
        el("li", {}, el("b", {}, "web/"), " — this site. Static files only; it reads the JSON and draws everything itself.")),
      el("div", { class: "hint hint--mint" },
        "Nothing on this site is typed in by hand. Change the engine, re-run the generator, and the pages follow.")));

  /* --------------------------------------------------------------- feature */
  const featured = el("section", {});
  const featuredRows = data.cases.filter((c) => c.names.length).slice(0, 4);
  if (featuredRows.length) {
    featured.append(
      el("div", { class: "section-head" },
        el("h2", {}, "Named cases"),
        el("span", { class: "panel__note" }, "The engine recognised these, verified the familiar algorithm against the goal, and publishes both it and its own shortest word."),
        el("span", { class: "spacer" }),
        el("a", { class: "btn btn--sm", href: "#/algorithms" }, "All cases")),
      el("div", { class: "grid grid--cases" }, featuredRows.map((r) => caseCard(r, { onOpen: openCase }))));
  }

  /* ------------------------------------------------------------- your path */
  const sessions = recentSessions().slice(0, 3);
  const you = el("section", { class: "panel" },
    el("div", { class: "panel__head" }, el("h3", {}, "Your progress"),
      el("span", { class: "spacer" }),
      el("a", { class: "btn btn--sm", href: "#/trainer" }, "Train")),
    el("div", { class: "stats" },
      stat(String(learnedCount(data.cases.map((c) => c.key))), "marked learned", `of ${int(t.cases)} cases`),
      stat(String(sessions.length), "recent sessions", sessions[0] ? `last: ${sessions[0].right}/${sessions[0].total} correct` : "none yet"),
      stat(t.fastest ? t.fastest.method : "—", "quickest method", t.fastest ? `${num(t.fastest.seconds.mean, 2)} s mean` : ""),
      stat(t.shortest ? t.shortest.method : "—", "fewest moves", t.shortest ? `${num(t.shortest.htm.mean, 2)} htm mean` : "")),
    el("p", { class: "tiny muted" },
      "Progress is stored in this browser only (localStorage). Export it from the Trainer if you want to keep it."));

  mount(view,
    hero,
    el("div", { class: "section-head" }, el("h2", {}, "The whole system in one line"),
      el("span", { class: "panel__note" }, `${int(t.elements)} last-layer elements · ${num(t.coverage, 2)}% swept · exact answers out to ${t.exactTo} moves`)),
    stats,
    el("div", { class: "section-head" }, el("h2", {}, "Pick your level"),
      el("span", { class: "panel__note" }, "Each level is a method plus the exact set of algorithms it asks you to know.")),
    levelCards,
    inside,
    featured,
    you);

  // start the showcase after paint, stop it when the view goes away
  requestAnimationFrame(() => { nextShowcase(); });

  return {
    node: view,
    destroy() {
      if (timer !== null) { clearTimeout(timer); timer = null; }
      panel.cube.stop();
    },
  };
}

function stat(value, key, sub = "", fox = false) {
  return el("div", { class: `stat ${fox ? "stat--fox" : ""}` },
    el("div", { class: "stat__k" }, key),
    el("div", { class: "stat__v" }, value),
    sub ? el("div", { class: "stat__s" }, sub) : null);
}
